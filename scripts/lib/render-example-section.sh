#!/usr/bin/env bash
# Render the ## Example markdown section from screenshots/*.png
# Usage: render-example-section.sh <screenshots-dir> <gist-base-url>
set -euo pipefail

SCREENSHOTS_DIR="$1"
BASE_URL="$2"

title_case() {
    echo "$1" | sed 's/-/ /g' | awk '{for(i=1;i<=NF;i++) $i=toupper(substr($i,1,1)) substr($i,2); print}'
}

label_for() {
    local filename="$1"
    local name="${filename%.png}"
    local prefix
    prefix=$(echo "$name" | cut -d'-' -f1)
    local rest
    rest=$(echo "$name" | cut -d'-' -f2-)

    case "$prefix" in
        settings)
            echo "Settings — $(title_case "$rest")"
            ;;
        onboarding)
            echo "Setup Wizard — $(title_case "$rest")"
            ;;
        *)
            title_case "$name"
            ;;
    esac
}

ORDER=(
    # 1. New user walks through the setup wizard
    onboarding-welcome.png
    onboarding-shell.png
    onboarding-tools.png
    onboarding-status-line.png
    onboarding-cli-flags.png
    onboarding-profiles.png
    # 2. App opens to its empty state
    empty-state.png
    # 3. Create and use a tab
    new-tab-sheet.png
    new-tab-sheet-filled.png
    main-window-tab.png
    # 4. Create and use a pane
    new-pane-sheet.png
    split-panes.png
    pane-status-indicators.png
    # 5. Notifications while working
    notification-sidebar.png
    pr-merged-alert.png
    # 6. Configure settings
    settings-panes.png
    settings-notifications.png
    settings-profiles.png
    settings-tools.png
    settings-shortcuts.png
    settings-status-line.png
    settings-debug.png
)

in_array() {
    local needle="$1"; shift
    for item in "$@"; do [[ "$item" == "$needle" ]] && return 0; done
    return 1
}

PNGS=()
for f in "${ORDER[@]}"; do
    [[ -f "$SCREENSHOTS_DIR/$f" ]] && PNGS+=("$f")
done
while IFS= read -r f; do
    base="$(basename "$f")"
    [[ -n "$base" ]] && ! in_array "$base" "${PNGS[@]}" && PNGS+=("$base")
done < <(ls "$SCREENSHOTS_DIR"/*.png 2>/dev/null | sort)

printf '\n## Example\n\n'

COUNT=${#PNGS[@]}
COLS=2
i=0
while [ "$i" -lt "$COUNT" ]; do
    header="|"
    sep="|"
    images="|"
    for j in $(seq 0 $(( COLS - 1 ))); do
        idx=$(( i + j ))
        if [ "$idx" -lt "$COUNT" ]; then
            png="${PNGS[$idx]}"
            lbl=$(label_for "$png")
            name="${png%.png}"
            header+=" $lbl |"
            sep+="---|"
            images+=" ![$name]($BASE_URL/$png) |"
        else
            header+="  |"
            sep+="---|"
            images+="  |"
        fi
    done

    echo "$header"
    echo "$sep"
    echo "$images"
    echo ""

    i=$(( i + COLS ))
done

printf '*Auto-generated by `make pr-screenshots`*\n'
